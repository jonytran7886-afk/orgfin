function makeConservativeScenario(): ScenarioData {
  const s = structuredClone(makeBaseScenario());
  s.id = 'conservative';
  s.name = 'Kịch bản Thận trọng';
  s.description = 'Giá mua đầu vào tăng nhẹ +5%, sản lượng tiêu thụ giảm 22%, hoãn mở cửa hàng số 2 để bảo toàn dòng tiền.';

  s.products = s.products.map((p) => ({
    ...p,
    purchasePricePerLiveKg: Math.round(p.purchasePricePerLiveKg * 1.05),
    targetSellPrice: Math.round(p.targetSellPrice * 0.96),
  }));

  s.channelPlans = s.channelPlans.map((cp) => ({
    ...cp,
    sellPrice: Math.round(cp.sellPrice * 0.96),
    monthlyVolumes: cp.monthlyVolumes.map((v) => Math.round(v * 0.78)),
  }));

  // Hoãn mở cửa hàng số 2 trong kịch bản thận trọng
  s.locations = s.locations.map((l) =>
    l.id === 'LOC-CH2' ? { ...l, isActive: false, note: 'Tạm hoãn mở điểm bán số 2 trong kịch bản thận trọng.' } : l
  );
  s.assets = s.assets.filter((a) => a.id !== 'TS-005');
  s.marketingCampaigns = s.marketingCampaigns.map((mc) => ({
    ...mc,
    adSpend: Math.round(mc.adSpend * 0.8),
  }));

  return s;
}

function makeGrowthScenario(): ScenarioData {
  const s = structuredClone(makeBaseScenario());
  s.id = 'growth';
  s.name = 'Kịch bản Tăng trưởng';
  s.description = 'Mở rộng kênh B2B và CTV (+30% sản lượng), tối ưu tỷ lệ thu hồi +2%, tăng ngân sách Marketing chuyển đổi.';

  s.products = s.products.map((p) => ({
    ...p,
    recoveryRate: p.group === 'Gà' ? Math.min(0.78, p.recoveryRate + 0.02) : p.recoveryRate,
    targetSellPrice: Math.round(p.targetSellPrice * 1.03),
  }));

  s.channelPlans = s.channelPlans.map((cp) => ({
    ...cp,
    sellPrice: Math.round(cp.sellPrice * 1.03),
    monthlyVolumes: cp.monthlyVolumes.map((v) => Math.round(v * 1.32)),
  }));

  s.marketingCampaigns = s.marketingCampaigns.map((mc) =>
    mc.pillar === 'conversion'
      ? {
          ...mc,
          adSpend: Math.round(mc.adSpend * 1.35),
          totalBudget: Math.round(mc.totalBudget * 1.3),
          orders: Math.round(mc.orders * 1.4),
          attributedRevenue: Math.round(mc.attributedRevenue * 1.45),
          attributedCmBeforeMkt: Math.round(mc.attributedCmBeforeMkt * 1.45),
        }
      : mc
  );

  return s;
}

export function createDefaultPlannerState(): PlannerState {
  const scenarios: Record<ScenarioId, ScenarioData> = {
    conservative: makeConservativeScenario(),
    base: makeBaseScenario(),
    growth: makeGrowthScenario(),
  };

  return {
    activeScenario: 'base',
    scenarios,
    lastSavedAt: new Date().toISOString(),
  };
}
